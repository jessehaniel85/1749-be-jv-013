-- Migration V1: tabela de usuários.
--
-- Como o Flyway funciona:
--   * Ele procura arquivos V<versão>__<descrição>.sql (DOIS underscores) e os executa em ordem.
--   * Registra cada um na tabela flyway_schema_history, com um checksum do conteúdo.
--   * Uma migration já executada NUNCA deve ser editada (o checksum muda e a aplicação não sobe).
--     Para mudar o banco, crie uma V3, V4... nova.

CREATE TABLE usuarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(30)  NOT NULL,
    -- guarda o HASH BCrypt (60 caracteres), NUNCA a senha. 100 deixa folga para outros algoritmos.
    senha_hash VARCHAR(100) NOT NULL,
    papel      VARCHAR(20)  NOT NULL DEFAULT 'USER',
    -- ativo = FALSE bloqueia o login sem apagar o usuário
    ativo      BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- a regra "username único" fica no BANCO, não só no código: protege contra duas requisições
    -- simultâneas criando o mesmo usuário.
    CONSTRAINT uk_usuarios_username UNIQUE (username),
    CONSTRAINT ck_usuarios_papel CHECK (papel IN ('USER', 'ADMIN'))
);
